import type { Meta, StoryObj } from '@storybook/react-vite';
import { useState } from 'react';
import {
  Avatar,
  Button,
  ChoiceButtons,
  Link,
  ReadingPane,
  ReadingPaneByline,
  ReadingPaneLead,
  ReadingPaneOutcome,
  ReadingPaneQuote,
  ReadingPaneReasoning,
  ReadingPaneSection,
  ReadingPaneTitle,
  Text,
} from '@crewlethq/ui';

/**
 * One item read in full, in one column: one sentence for who is asking and
 * about which task, the question in large type, its context, the reasoning
 * with its evidence, the answer, and the conversation.
 */
const meta: Meta<typeof ReadingPane> = {
  title: 'UI/ReadingPane',
  component: ReadingPane,
};

export default meta;
type Story = StoryObj<typeof ReadingPane>;

const task = (
  <Link href="#/worklet/FAIR-3" variant="quiet" size="inherit">
    FAIR-3 Ledger and settlement
  </Link>
);

function Question() {
  const [answer, setAnswer] = useState<string | null>(null);
  return (
    <ReadingPane>
      <ReadingPaneByline leading={<Avatar name="Crewlet-PM" size={20} decorative />}>
        <strong>Crewlet-PM</strong> asks for your approval on {task}
      </ReadingPaneByline>
      <ReadingPaneTitle>Should settlement use greedy matching only, or an exact search?</ReadingPaneTitle>
      <ReadingPaneLead>
        <p>Both pass the ledger tests. Exact search needs fewer transfers but slows down past forty people.</p>
      </ReadingPaneLead>
      <ReadingPaneReasoning
        title={
          <>
            Crewlet-PM recommends <strong>Exact search</strong>
          </>
        }
        footer={
          <Link href="#/doclet/settlement" variant="quiet" size="caption">
            Settlement notes
          </Link>
        }
      >
        <p>Groups in the beta are under twenty people, where the search finishes in under a second.</p>
      </ReadingPaneReasoning>
      {answer ? (
        <ReadingPaneOutcome>
          Answered <strong>{answer}</strong>
        </ReadingPaneOutcome>
      ) : (
        <ChoiceButtons
          label="Answers"
          recommended="exact"
          options={[
            { value: 'greedy', label: 'Greedy matching only' },
            { value: 'exact', label: 'Exact search' },
          ]}
          onChoose={(value) => setAnswer(value === 'exact' ? 'Exact search' : 'Greedy matching only')}
        />
      )}
      <Text as="p" variant="caption">
        Your answer is also posted to #product.
      </Text>
      <ReadingPaneSection label="Replies to this question">
        <Text as="p" variant="caption">
          No replies yet.
        </Text>
      </ReadingPaneSection>
    </ReadingPane>
  );
}

export const AQuestion: Story = {
  render: () => (
    <div style={{ background: 'var(--color-surface-background)' }}>
      <Question />
    </div>
  ),
};

